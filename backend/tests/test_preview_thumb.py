"""Tests for the overview (grid) thumbnail endpoint /preprocessing/preview-thumb."""

from io import BytesIO

import pytest
from fastapi.testclient import TestClient
from PIL import Image

import api.services.preprocessing_cache as pc
from api.server import app


@pytest.fixture
def client(tmp_path, monkeypatch):
    """A client whose preprocessing cache lives under tmp_path (no real ~/.cache)."""
    # Point the cache at a temp dir and force a fresh singleton.
    monkeypatch.setattr(pc.PreprocessingCache, "DEFAULT_CACHE_DIR", tmp_path / "cache")
    pc.reset_cache()
    yield TestClient(app)
    pc.reset_cache()


def _make_jpeg(path, size=(1200, 800), color=(120, 60, 30)):
    Image.new("RGB", size, color).save(path, format="JPEG", quality=90)


def test_downscales_jpeg_within_size(client, tmp_path):
    img = tmp_path / "photo.jpg"
    _make_jpeg(img)

    resp = client.get("/api/v1/preprocessing/preview-thumb", params={"path": str(img), "size": 256})

    assert resp.status_code == 200
    assert resp.headers["content-type"] == "image/jpeg"
    assert resp.headers["X-Cache"] == "MISS"
    out = Image.open(BytesIO(resp.content))
    assert out.format == "JPEG"
    assert max(out.size) <= 256


def test_second_request_is_cache_hit(client, tmp_path):
    img = tmp_path / "photo.jpg"
    _make_jpeg(img)

    first = client.get(
        "/api/v1/preprocessing/preview-thumb", params={"path": str(img), "size": 256}
    )
    second = client.get(
        "/api/v1/preprocessing/preview-thumb", params={"path": str(img), "size": 256}
    )

    assert first.headers["X-Cache"] == "MISS"
    assert second.headers["X-Cache"] == "HIT"
    assert second.content == first.content


def test_honours_exif_orientation(client, tmp_path):
    # A landscape image tagged as rotated 90° (orientation 6) should come back
    # portrait after exif_transpose.
    img = tmp_path / "rot.jpg"
    exif = Image.Exif()
    exif[0x0112] = 6  # Orientation: rotate 90° CW
    Image.new("RGB", (400, 200), (10, 120, 200)).save(img, format="JPEG", exif=exif)

    resp = client.get("/api/v1/preprocessing/preview-thumb", params={"path": str(img), "size": 256})

    assert resp.status_code == 200
    out = Image.open(BytesIO(resp.content))
    # 400x200 rotated becomes portrait (height > width).
    assert out.height > out.width


