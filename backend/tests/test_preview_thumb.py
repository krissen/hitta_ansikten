def test_tiny_cache_still_serves_valid_jpeg(client, tmp_path):
    # With a zero-size cache, store_grid_thumb's LRU eviction removes the file
    # immediately — the endpoint must still return the generated bytes, not 500.
    from api.services.preprocessing_cache import get_cache

    get_cache().set_max_size(0)

    img = tmp_path / "photo.jpg"
    _make_jpeg(img)

    first = client.get(
        "/api/v1/preprocessing/preview-thumb", params={"path": str(img), "size": 256}
    )
    second = client.get(
        "/api/v1/preprocessing/preview-thumb", params={"path": str(img), "size": 256}
    )

    assert first.status_code == 200
    assert second.status_code == 200
    assert Image.open(BytesIO(first.content)).format == "JPEG"
    # Nothing survives in the zero-size cache, so every request is a MISS.
    assert first.headers["X-Cache"] == "MISS"
    assert second.headers["X-Cache"] == "MISS"


def test_different_size_is_separate_cache_entry(client, tmp_path):
    img = tmp_path / "photo.jpg"
    _make_jpeg(img)

    r256 = client.get("/api/v1/preprocessing/preview-thumb", params={"path": str(img), "size": 256})
    r128 = client.get("/api/v1/preprocessing/preview-thumb", params={"path": str(img), "size": 128})

    assert r256.headers["X-Cache"] == "MISS"
    assert r128.headers["X-Cache"] == "MISS"  # size is part of the key
    assert max(Image.open(BytesIO(r128.content)).size) <= 128
